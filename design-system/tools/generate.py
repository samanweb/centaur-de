        ("menu.separator.padding.width", px(scale["space"]["md"])),
        ("menu.separator.padding.height", px(scale["space"]["sm"])),
        ("menu.separator.color", border["subtle"]),
        ("menu.title.bg.color", surface["overlay"]),
        ("menu.title.text.color", text["muted"]),
        ("menu.title.text.justify", "Left"),
        ("", None),
        ("# window switcher (Alt+Tab) and other on-screen displays", None),
