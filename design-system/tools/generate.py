        ("window.inactive.border.color", border["subtle"]),
        ("window.active.indicator.toggled-keybind.color", status["danger"]),
        ("window.active.title.bg.color", surface["sidebar"]),
        ("window.inactive.title.bg.color", surface["window"]),
        ("window.*.title.bg", "Solid"),
        ("window.active.label.text.color", text["primary"]),
        ("window.inactive.label.text.color", text["muted"]),
        ("window.label.text.justify", "center"),
        ("", None),
        ("# titlebar buttons", None),
        ("window.button.width", "28"),
        ("window.button.height", "28"),
        ("window.button.spacing", px(scale["space"]["xs"])),
        ("window.button.hover.bg.color", hover),
        ("window.button.hover.bg.corner-radius", px(scale["radius"]["sm"])),
        ("window.active.button.unpressed.image.color", text["secondary"]),
        ("window.inactive.button.unpressed.image.color", text["muted"]),
        ("", None),
