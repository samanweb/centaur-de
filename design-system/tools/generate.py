def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=pathlib.Path,
                    default=ROOT.parent / "app" / "data" / "themes")
    ap.add_argument("--preview", type=pathlib.Path,
                    help="also write an HTML swatch sheet here")
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if output would change")
    args = ap.parse_args()

    data = load()
    artifacts: dict[pathlib.Path, str] = {}

    for palette_name in data["palettes"]:
        artifacts[args.out / f"tokens-{palette_name}.css"] = palette_css(data, palette_name)
        for accent_name in data["accents"]:
            artifacts[args.out / "accents" / f"{accent_name}-{palette_name}.css"] = \
                accent_css(data, palette_name, accent_name)

    artifacts[args.out / "components.css"] = components_css(data)
    artifacts[args.out / "accent-map.json"] = accent_map(data)
    artifacts[args.out / "swaylock.conf"] = swaylock_config(data)
    for palette_name in data["palettes"]:
        for accent_name in data["accents"]:
            name = f"Centaur-{accent_name}-{palette_name}"
            artifacts[args.out.parent / "labwc-themes" / name / "labwc" / "themerc"] = \
                labwc_themerc(data, palette_name, accent_name)
    for palette_name, accent_name in WALLPAPERS:
        name = f"centaur-{accent_name}-{palette_name}.svg"
        artifacts[args.out.parent / "backgrounds" / name] = \
            wallpaper_svg(data, palette_name, accent_name)

    if args.check:
        stale = [p for p, body in artifacts.items()
                 if not p.exists() or p.read_text() != body]
        if stale:
            print("stale generated output:", file=sys.stderr)
            for path in stale:
                print(f"  {path}", file=sys.stderr)
            print("run design-system/tools/generate.py", file=sys.stderr)
            return 1
        print(f"up to date ({len(artifacts)} files)")
        return 0

    for path, body in artifacts.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)

    if args.preview:
        args.preview.parent.mkdir(parents=True, exist_ok=True)
        args.preview.write_text(preview_html(data))
        print(f"wrote {args.preview}")

    print(f"wrote {len(artifacts)} files to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
