        ("window.inactive.shadow.color", shadow_inactive),
        ("", None),
        ("# menus: the desktop (root) menu and each window's menu", None),
        ("menu.overlap.x", "0"),
        ("menu.overlap.y", "0"),
        ("menu.width.min", "200"),
        ("menu.width.max", "320"),
        ("menu.border.width", "1"),
        ("menu.border.color", border["default"]),
        ("menu.items.bg.color", surface["overlay"]),
        ("menu.items.text.color", text["primary"]),
        ("menu.items.active.bg.color", highlight),
        ("menu.items.active.text.color", text["primary"]),
